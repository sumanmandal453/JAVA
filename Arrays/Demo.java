package Arrays;

public class Demo {
    public static void main(String[] args){
        int[] roll_num = new int[3];
        // 101,102,103

        roll_num[0] = 101;
        roll_num[1] = 102;
        roll_num[2] = 103;

        System.out.println("1st roll_number is: "+ roll_num[0]);
        System.out.println("2nd roll_number is: " + roll_num[1]);
        System.out.println("3rd roll_number is: " + roll_num[2]);

        System.out.println("The length of the indexing is: " + roll_num.length);



    }
}
